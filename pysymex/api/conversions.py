"""Configuration coercion helpers for the public API."""

from __future__ import annotations

from pysymex.logger import get_logger

logger = get_logger(__name__)


def to_int(value: object, default: int) -> int:
    """Convert a generic config value to int, returning the default on invalid input."""
    if isinstance(value, bool):
        return int(value)
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        return int(value)
    if isinstance(value, str):
        try:
            return int(value)
        except ValueError:
            logger.debug("Using default int config value for %r", value)
            return default
    return default


def to_float(value: object, default: float) -> float:
    """Convert a generic config value to float, returning the default on invalid input."""
    if isinstance(value, bool):
        return float(value)
    if isinstance(value, (int, float)):
        return float(value)
    if isinstance(value, str):
        try:
            return float(value)
        except ValueError:
            logger.debug("Using default float config value for %r", value)
            return default
    return default


def to_bool(value: object, default: bool) -> bool:
    """Convert a generic config value to bool, returning the default on invalid input."""
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return bool(value)
    if isinstance(value, str):
        lowered = value.strip().lower()
        if lowered in {"1", "true", "yes", "on"}:
            return True
        if lowered in {"0", "false", "no", "off"}:
            return False
    return default
