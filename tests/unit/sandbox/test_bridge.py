def _is_object_tuple(value: object) -> TypeGuard[tuple[object, ...]]:
    return isinstance(value, tuple)


def _is_object_frozenset(value: object) -> TypeGuard[frozenset[object]]:
    return isinstance(value, frozenset)


def _is_object_mapping(value: object) -> TypeGuard[Mapping[str, object]]:
    return isinstance(value, Mapping)


def _serialize_code_for_bridge(code_obj: CodeType, filename: str) -> dict[str, object]:
    def _serialize_constant(constant: object) -> object:
        if isinstance(constant, CodeType):
            return _serialize_code_for_bridge(constant, filename)
        if _is_object_tuple(constant):
            return {"_type": "tuple", "value": [_serialize_constant(item) for item in constant]}
        if _is_object_frozenset(constant):
            return {
                "_type": "frozenset",
                "value": [_serialize_constant(item) for item in constant],
            }
        if isinstance(constant, bytes):
            return {"_type": "bytes", "value": base64.b64encode(constant).decode("ascii")}
        if isinstance(constant, (int, float, str, type(None), bool)):
            return constant
        return None

    serialized: dict[str, object] = {
        "co_argcount": code_obj.co_argcount,
        "co_posonlyargcount": code_obj.co_posonlyargcount,
        "co_kwonlyargcount": code_obj.co_kwonlyargcount,
        "co_nlocals": code_obj.co_nlocals,
        "co_stacksize": code_obj.co_stacksize,
        "co_flags": code_obj.co_flags,
        "co_code": base64.b64encode(code_obj.co_code).decode("ascii"),
        "co_names": list(code_obj.co_names),
        "co_varnames": list(code_obj.co_varnames),
        "co_freevars": list(code_obj.co_freevars),
        "co_cellvars": list(code_obj.co_cellvars),
        "co_filename": filename,
        "co_name": code_obj.co_name,
        "co_firstlineno": code_obj.co_firstlineno,
        "_type": "CodeType",
        "co_qualname": code_obj.co_qualname,
        "co_linetable": base64.b64encode(code_obj.co_linetable).decode("ascii"),
        "co_exceptiontable": base64.b64encode(code_obj.co_exceptiontable).decode("ascii"),
    }
    serialized["co_consts"] = [_serialize_constant(constant) for constant in code_obj.co_consts]
    return serialized


def _create_bridge_payload(code_obj: CodeType, filename: str) -> bytes:
    return json.dumps(_serialize_code_for_bridge(code_obj, filename)).encode("utf-8")


